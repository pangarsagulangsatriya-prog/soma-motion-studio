import {test,expect} from '@playwright/test';
const archive={name:'archive-red.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="900"><rect width="1600" height="900" fill="#d02020"/></svg>')};
test('V5.1 real archive preview, next cue isolation and latched blackout',async({page})=>{
 await page.goto('/?workspace=nodes');
 await expect(page.locator('.soma-signal[data-version="5.1"]')).toBeVisible();
 await expect(page.locator('.sw-node')).toHaveCount(13);
 await expect(page.getByRole('button',{name:'GO',exact:true})).toBeDisabled();
 await page.locator('[data-node="archive"] .sw-node-title').click();
 await page.locator('.sw-inspector input[type=file]').setInputFiles(archive);
 await page.getByRole('button',{name:'F2 Arsip',exact:true}).click();
 await expect(page.getByRole('button',{name:'GO',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'GO',exact:true}).click();
 const pixel=async(s)=>page.locator('.sw-monitor[data-surface="'+s+'"] canvas').evaluate(c=>Array.from(c.getContext('2d').getImageData(800,450,1,1).data));
 await expect.poll(async()=> (await pixel('canvas'))[0]).toBeGreaterThan(170);
 expect((await pixel('floor'))[0]).toBe(0);
 await page.getByRole('button',{name:'F1 Jejak',exact:true}).click();
 await expect(page.locator('.sw-current b')).toHaveText('F2');
 await expect(page.getByRole('button',{name:'GO',exact:true})).toBeDisabled();
 expect((await pixel('canvas'))[0]).toBeGreaterThan(170);
 await page.getByRole('button',{name:'Blackout semua output'}).click();
 await expect.poll(async()=> (await pixel('canvas'))[0]).toBe(0);
 await expect(page.locator('.sw-current b')).toHaveText('F2');
 await page.getByRole('button',{name:'Resume Canvas',exact:true}).click();
 await expect.poll(async()=> (await pixel('canvas'))[0]).toBeGreaterThan(170);
 expect((await pixel('floor'))[0]).toBe(0);
 await page.getByRole('button',{name:'Stop cue'}).click();
 await expect(page.locator('.sw-current b')).toHaveText('—');
 await expect.poll(async()=> (await pixel('canvas'))[0]).toBe(0);
});
test('V5.1 grouped graph, keyboard layout, compact controls and reduced motion',async({page})=>{
 await page.goto('/?workspace=nodes');
 await expect(page.locator('[data-node="session"]')).toHaveCount(1);
 await expect(page.locator('[data-node="floor"]')).toHaveCount(1);
 await expect(page.locator('[data-node="canvas"]')).toHaveCount(1);
 const node=page.locator('[data-node="foot"]');const before=await node.evaluate(n=>n.style.left);
 await node.locator('.sw-node-title').focus();await page.keyboard.press('ArrowRight');
 await expect.poll(()=>node.evaluate(n=>n.style.left)).not.toBe(before);
 await page.getByRole('button',{name:'Reset layout'}).click();
 await expect.poll(()=>node.evaluate(n=>n.style.left)).toBe(before);
 await page.getByLabel('Workspace settings').click();await page.getByLabel('Kurangi animasi').check();
 await expect(page.locator('.soma-signal')).toHaveAttribute('data-reduced-motion','true');
 await expect(page.getByRole('button',{name:'Blackout semua output'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Record F1'})).toBeVisible();
});
