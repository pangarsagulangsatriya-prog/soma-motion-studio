import React from 'react';
import {createRoot} from 'react-dom/client';
import App from './App';
import {UnifiedNodeWorkspace} from './studio/v5/UnifiedNodeWorkspace.tsx';
import {SignalWorkspace} from './studio/v51/SignalWorkspace.tsx';
import {StageTwoApp} from './studio/v3/StageTwoApp.tsx';
import './style.css';
import './v2.css';
import './archive/archive.css';
import ProjectionOutput from './projection/ProjectionOutput';
import ProjectionScreen from './archive/ProjectionScreen';
import {PhoneCameraSender} from './stage/PhoneCameraSender.tsx';
import {StageSessionProvider} from './stage/StageSessionProvider.tsx';
const query=new URLSearchParams(location.search);
const phoneCamera=query.get('phoneCamera')==='1';
const bodyProjection=query.get('bodyProjection');
const stageSurface=new URLSearchParams(location.search).get('stageSurface');
const role=stageSurface==='body'||stageSurface==='floor'?stageSurface:undefined;
const projection=new URLSearchParams(location.search).get('projection');
const stageTwo=query.get('stage')==='2';
createRoot(document.getElementById('root')!).render(<React.StrictMode>{phoneCamera?<PhoneCameraSender/>:bodyProjection?<ProjectionOutput session={bodyProjection} surface={role}/>:projection?<ProjectionScreen sessionId={projection}/>:stageTwo?<StageTwoApp/>:query.get('workspace')==='nodes-v5'?<UnifiedNodeWorkspace/>:query.get('workspace')==='nodes'?<SignalWorkspace/>:<StageSessionProvider><App/></StageSessionProvider>}</React.StrictMode>);
