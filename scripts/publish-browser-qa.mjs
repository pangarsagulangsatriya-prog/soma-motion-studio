/** Publish Playwright QA outcome to a standalone branch for review.
 * Called only by the browser-qa workflow after the test runner exits. */
import {existsSync,mkdirSync,readFileSync,writeFileSync,cpSync,rmSync} from 'node:fs';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';

const exec=(cmd,args,allowFailure=false)=>{
 const r=spawnSync(cmd,args,{stdio:'inherit',encoding:'utf8'});
 if(r.status!==0&&!allowFailure)throw Error(cmd+' '+args.join(' ')+' failed ('+r.status+')');
 return r.status===0;
};
const outcome=process.env.QA_OUTCOME||'unknown';
const runId=process.env.GITHUB_RUN_ID||'unknown';
const sha=process.env.GITHUB_SHA||'unknown';
const statsFile='e2e/qa-result.json';
let stats=null;
try{
 stats=JSON.parse(readFileSync(statsFile,'utf8')).stats;
}catch{}
const temp=mkdtempSync(join(tmpdir(),'soma-browser-qa-'));
const srcShots='e2e/artifacts';
const dstShots=join(temp,'screenshots');
if(existsSync(srcShots))cpSync(srcShots,dstShots,{recursive:true});
const table=[
 ['Expected passed',stats?.expected??'unknown'],
 ['Unexpected failed',stats?.unexpected??'unknown'],
 ['Flaky',stats?.flaky??'unknown'],
 ['Skipped',stats?.skipped??'unknown']
].map(([a,b])=>'| '+a+' | '+b+' |').join('\n');
const repo='pangarsagulangsatriya-prog/soma-motion-studio';
const report=`# SOMA — S6.7.2.5 Browser QA

**Result:** ${outcome.toUpperCase()}  
**Commit:** \`${sha}\`  
**Run:** [GitHub Actions #${runId}](https://github.com/${repo}/actions/runs/${runId})  
**Generated:** ${new Date().toISOString()}  

## Playwright results

| Metric | Count |
|---|---:|
${table}

## Checked browser viewports

- Desktop 1440 × 900
- Laptop 1366 × 768
- Tablet 1024 × 768
- Mobile 390 × 844

## Test scope

Source selection, unavailable camera recovery, Source → Tracking → Visual & Archive → Projector navigation, local Inspector/Escape focus, SOMA Labs, software Blackout access, popup safety, horizontal overflow and screenshots.

## Device-level limits

**This report does not certify hardware safety.** Camera permissions and denial are simulated. Real camera feed, phone pairing, two actual performers, projectors, electrical shutoff and optical alignment require stage hardware validation before a live performance.

## Screenshots

Screenshots generated by successful tests are in the [screenshots](./screenshots) folder if any were captured. Failure traces, full HTML report and run artifacts remain available from the GitHub Actions run above.
`;
writeFileSync(join(temp,'README.md'),report);
const onRemote=spawnSync('git',['ls-remote','--exit-code','--heads','origin','qa-results'],
 {encoding:'utf8'}).status===0;
if(onRemote){
 exec('git',['fetch','origin','qa-results']);
 exec('git',['checkout','-B','qa-results','FETCH_HEAD']);
}else{
 exec('git',['checkout','--orphan','qa-results']);
 exec('git',['rm','-rf','.'],true);
}
rmSync('screenshots',{recursive:true,force:true});
cpSync(join(temp,'README.md'),'README.md');
if(existsSync(dstShots))cpSync(dstShots,'screenshots',{recursive:true});
exec('git',['config','user.name','github-actions[bot]']);
exec('git',['config','user.email','41898282+github-actions[bot]@users.noreply.github.com']);
exec('git',['add','README.md']);
if(existsSync('screenshots'))exec('git',['add','screenshots']);
if(exec('git',['diff','--cached','--quiet'],true)){
 // No changes to publish.
}else{
 exec('git',['commit','-m','qa: browser acceptance '+outcome+' for '+sha.slice(0,8)]);
 exec('git',['push','origin','qa-results']);
}
